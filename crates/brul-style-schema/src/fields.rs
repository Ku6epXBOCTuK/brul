use crate::{
    Converter, FieldDefault, FieldSpec, FieldType, PatchField, PatchTarget, ShadowPart, Side,
    Side::*, SidesType, StyleOwner, TweenKind,
};

pub const fn patch(name: &'static str, order: u16, converter: Converter) -> PatchField {
    PatchField {
        name,
        order,
        target: PatchTarget::This,
        converter,
    }
}

pub const fn side_patch(
    name: &'static str,
    order: u16,
    side: Side,
    converter: Converter,
) -> PatchField {
    PatchField {
        name,
        order,
        target: PatchTarget::Side(side),
        converter,
    }
}

pub const fn sub_patch(
    name: &'static str,
    order: u16,
    part: ShadowPart,
    converter: Converter,
) -> PatchField {
    PatchField {
        name,
        order,
        target: PatchTarget::Shadow(part),
        converter,
    }
}

pub const fn scaled_patch(name: &'static str, order: u16, factor: f32) -> PatchField {
    PatchField {
        name,
        order,
        target: PatchTarget::Scaled(factor),
        converter: Converter::Float,
    }
}

pub const fn field(
    owner: StyleOwner,
    name: &'static str,
    ty: FieldType,
    default: FieldDefault,
    tween: TweenKind,
    patches: &'static [PatchField],
) -> FieldSpec {
    FieldSpec {
        owner,
        name,
        ty,
        default,
        tween,
        patches,
    }
}

