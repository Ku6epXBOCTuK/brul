#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Side {
    Left,
    Top,
    Right,
    Bottom,
}

impl Side {
    pub const ALL: [Side; 4] = [Side::Left, Side::Top, Side::Right, Side::Bottom];
}

#[derive(Clone, Copy, Debug, PartialEq)]
pub enum Type {
    ThemeKey,
    Number,
    Px,
    SignedPx,
    Length,
    Color,
    Paint,
    String,
    Bool,
    Keywords(&'static [&'static str]),
    TrackList,
    GridLine,
    AreaTemplate,
    GridArea,
    NumberRange(f64, f64),
    NumberIn(&'static [f64]),
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum StatePolicy {
    Forbidden,
    Visual,
    TextWeight,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum LayoutField {
    Width,
    Height,
    FlexGrow,
    FlexShrink,
    FlexBasis,
    Display,
    FlexDirection,
    GridTemplateColumns,
    GridTemplateRows,
    GridColumn,
    GridRow,
    GridAutoFlow,
    GridTemplateAreas,
    GridArea,
    Padding(Side),
    Gap,
    RowGap,
    ColumnGap,
    BorderWidthSide(Side),
    Justify,
    Align,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum StyleField {
    Background,
    BorderSide(Side),
    Text,
    Tint,
    BorderRadius,
    Opacity,
    Clip,
    Scroll,
    ShadowX,
    ShadowY,
    ShadowBlur,
    ShadowColor,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum TextField {
    Size,
    Family,
    Align,
    VerticalAlign,
    Weight,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Target {
    Layout(LayoutField),
    Style(StyleField),
    Text(TextField),
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum PropertyKey {
    Width,
    Height,
    FlexGrow,
    FlexShrink,
    FlexBasis,
    Display,
    FlexDirection,
    GridTemplateColumns,
    GridTemplateRows,
    GridColumn,
    GridRow,
    GridAutoFlow,
    GridTemplateAreas,
    GridArea,
    PaddingSide(Side),
    Gap,
    RowGap,
    ColumnGap,
    BorderWidthSide(Side),
    BorderRadius,
    FontSize,
    FontFamily,
    JustifyContent,
    AlignItems,
    Background,
    BorderColorSide(Side),
    Color,
    Tint,
    TextAlign,
    VerticalAlign,
    FontWeight,
    Opacity,
    Clip,
    Scroll,
    ShadowOffsetX,
    ShadowOffsetY,
    ShadowBlur,
    ShadowColor,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum DefaultValue {
    Default,
}

#[derive(Clone, Copy)]
pub struct PropertySpec {
    pub key: PropertyKey,
    pub name: &'static str,
    pub ty: Type,
    pub in_state: StatePolicy,
    pub target: Target,
    pub animatable: bool,
    pub default: DefaultValue,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ShorthandParser {
    Box,
    Border,
    BorderColor,
    Shadow,
}

#[derive(Clone, Copy)]
pub struct ShorthandSpec {
    pub name: &'static str,
    pub expands_to: &'static [PropertyKey],
    pub parser: ShorthandParser,
}

#[derive(Clone, Copy)]
pub enum FieldSpec {
    Scalar(PropertyKey),
    Sides(&'static str, &'static str),
    Parts(&'static [PropertyKey]),
}

