#[derive(Clone, Copy)]
pub struct PatchField {
    pub name: &'static str,
    pub order: u16,
    pub target: PatchTarget,
    pub converter: Converter,
}

#[derive(Clone, Copy)]
pub struct FieldSpec {
    pub owner: StyleOwner,
    pub name: &'static str,
    pub ty: FieldType,
    pub default: FieldDefault,
    pub tween: TweenKind,
    pub patches: &'static [PatchField],
}

pub const fn patch(name: &'static str, order: u16, converter: Converter) -> PatchField {
    PatchField {
        name,
        order,
        target: PatchTarget::This,
        converter,
    }
}

pub const fn side_patch(
    name: &'static str,
    order: u16,
    side: Side,
    converter: Converter,
) -> PatchField {
    PatchField {
        name,
        order,
        target: PatchTarget::Side(side),
        converter,
    }
}

pub const fn sub_patch(
    name: &'static str,
    order: u16,
    subfield: &'static str,
    converter: Converter,
) -> PatchField {
    PatchField {
        name,
        order,
        target: PatchTarget::Subfield(subfield),
        converter,
    }
}

pub const fn scaled_patch(name: &'static str, order: u16, from: &'static str) -> PatchField {
    PatchField {
        name,
        order,
        target: PatchTarget::Scaled(from),
        converter: Converter::Float,
    }
}

pub const fn field(
    owner: StyleOwner,
    name: &'static str,
    ty: FieldType,
    default: FieldDefault,
    tween: TweenKind,
    patches: &'static [PatchField],
) -> FieldSpec {
    FieldSpec {
        owner,
        name,
        ty,
        default,
        tween,
        patches,
    }
}

