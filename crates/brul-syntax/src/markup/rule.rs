#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Rule {
    File,
    ComponentDecl,
    WindowDecl,
    Member,
    PropDecl,
    PropType,
    EventDecl,
    EventParamList,
    EventParam,
    Element,
    ArgList,
    Arg,
    HandlerRef,
    Block,
    BlockItem,
    IfBlock,
    EachBlock,
    EventName,
    Ident,
}

impl Rule {
    pub const ALL: &[Rule] = &[
        Rule::File,
        Rule::ComponentDecl,
        Rule::WindowDecl,
        Rule::Member,
        Rule::PropDecl,
        Rule::PropType,
        Rule::EventDecl,
        Rule::EventParamList,
        Rule::EventParam,
        Rule::Element,
        Rule::ArgList,
        Rule::Arg,
        Rule::HandlerRef,
        Rule::Block,
        Rule::BlockItem,
        Rule::IfBlock,
        Rule::EachBlock,
        Rule::EventName,
        Rule::Ident,
    ];

    pub fn name(self) -> &'static str {
        match self {
            Rule::File => "File",
            Rule::ComponentDecl => "ComponentDecl",
            Rule::WindowDecl => "WindowDecl",
            Rule::Member => "Member",
            Rule::PropDecl => "PropDecl",
            Rule::PropType => "PropType",
            Rule::EventDecl => "EventDecl",
            Rule::EventParamList => "EventParamList",
            Rule::EventParam => "EventParam",
            Rule::Element => "Element",
            Rule::ArgList => "ArgList",
            Rule::Arg => "Arg",
            Rule::HandlerRef => "HandlerRef",
            Rule::Block => "Block",
            Rule::BlockItem => "BlockItem",
            Rule::IfBlock => "IfBlock",
            Rule::EachBlock => "EachBlock",
            Rule::EventName => "EventName",
            Rule::Ident => "Ident",
        }
    }
}
