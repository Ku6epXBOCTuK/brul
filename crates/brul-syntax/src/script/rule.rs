#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Rule {
    Expr,
    Assignment,
    Ternary,
    LogicOr,
    LogicAnd,
    Equality,
    Comparison,
    Term,
    Factor,
    Unary,
    Postfix,
    Primary,
    ArgList,
    Array,
    Object,
    Template,
    Program,
    ImportStmt,
    FunctionDecl,
    ParamList,
    Statement,
    LetStmt,
    IfStmt,
    ExprStmt,
    Block,
    Ident,
    Number,
    String,
    TemplateChar,
}

impl Rule {
    pub const ALL: &[Rule] = &[
        Rule::Expr,
        Rule::Assignment,
        Rule::Ternary,
        Rule::LogicOr,
        Rule::LogicAnd,
        Rule::Equality,
        Rule::Comparison,
        Rule::Term,
        Rule::Factor,
        Rule::Unary,
        Rule::Postfix,
        Rule::Primary,
        Rule::ArgList,
        Rule::Array,
        Rule::Object,
        Rule::Template,
        Rule::Program,
        Rule::ImportStmt,
        Rule::FunctionDecl,
        Rule::ParamList,
        Rule::Statement,
        Rule::LetStmt,
        Rule::IfStmt,
        Rule::ExprStmt,
        Rule::Block,
        Rule::Ident,
        Rule::Number,
        Rule::String,
        Rule::TemplateChar,
    ];

    pub fn name(self) -> &'static str {
        match self {
            Rule::Expr => "Expr",
            Rule::Assignment => "Assignment",
            Rule::Ternary => "Ternary",
            Rule::LogicOr => "LogicOr",
            Rule::LogicAnd => "LogicAnd",
            Rule::Equality => "Equality",
            Rule::Comparison => "Comparison",
            Rule::Term => "Term",
            Rule::Factor => "Factor",
            Rule::Unary => "Unary",
            Rule::Postfix => "Postfix",
            Rule::Primary => "Primary",
            Rule::ArgList => "ArgList",
            Rule::Array => "Array",
            Rule::Object => "Object",
            Rule::Template => "Template",
            Rule::Program => "Program",
            Rule::ImportStmt => "ImportStmt",
            Rule::FunctionDecl => "FunctionDecl",
            Rule::ParamList => "ParamList",
            Rule::Statement => "Statement",
            Rule::LetStmt => "LetStmt",
            Rule::IfStmt => "IfStmt",
            Rule::ExprStmt => "ExprStmt",
            Rule::Block => "Block",
            Rule::Ident => "Ident",
            Rule::Number => "Number",
            Rule::String => "String",
            Rule::TemplateChar => "TemplateChar",
        }
    }
}
