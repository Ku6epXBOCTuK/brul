//! Реактивное ядро BRUL: сигналы, memo и эффекты.
//!
//! # Модель
//!
//! Граф однопоточный и живёт на UI-потоке вместе с рендером. Узел — `Signal`,
//! `Memo` или `Effect`; ребро — зависимость «этот узел читает тот». Сигнал
//! хранит список подписчиков, подписчик — список своих зависимостей. Оба
//! списка двусвязные, поэтому подписка снимается за постоянное время, без
//! поиска по списку.
//!
//! Расчёт идёт в два такта:
//!
//! 1. запись в сигнал помечает подписчиков грязными и ничего не считает;
//! 2. чтение грязного memo пересчитывает только зависимости, чьи версии
//!    изменились.
//!
//! Эффект — исключение из ленивости: его никто не читает, поэтому он
//! планируется сам и выполняется один раз за кадр, после батча и до отрисовки.
//!
//! # Инварианты
//!
//! - В графе нет `Rc`, `RefCell` и `Box<dyn>`: связи — индексы в арене
//!   `Vec<Node>`, значения — в типизированном хранилище.
//! - Рекурсии по графу нет: пометка и проверка идут на явном стеке, поэтому
//!   глубина зависимостей ограничена размером арены, а не стека потока.
//! - Узел пересчитывается не больше одного раза за проход.
//! - Чтение подписывает только внутри вычисления (`Memo`, `Effect`). Вне их
//!   чтение подписки не создаёт; `untrack` выключает подписку на время
//!   замыкания.
//! - Запись из эффекта разрешена: она ставит в очередь ещё один проход того же
//!   flush, а не перезапускает текущий.
//! - Дескрипторы — `Copy`-индексы, `!Send` и `!Sync`. Передать их в
//!   tokio-задачу нельзя: фоновое обновление приходит через канал на UI-поток.
//!
//! # Алгоритм
//!
//! Ядро повторяет push-pull из
//! [alien-signals](https://github.com/stackblitz-labs/alien-signals): у каждого
//! узла есть флаги и монотонная версия.
//!
//! - `propagate` — push-такт. Идёт по списку подписчиков, ставит `Dirty`;
//!   наблюдаемые узлы (те, у кого есть эффекты) продолжают пометку вверх по
//!   графу. Флаг `Recursed` не даёт обойти узел дважды.
//! - `checkDirty` — pull-такт при чтении memo. Спускается по зависимостям и
//!   сравнивает версии: если грязный memo зависит только от чистых узлов,
//!   пересчёт пропускается.
//! - `Watched` помечает поддерево, у которого есть живой эффект; только оно
//!   нуждается в push-такте, остальные узлы спят до чтения.
//!
//! # Публичный API
//!
//! Сигнатуры повторяют `reactive_graph`, чтобы замена ядра была механической.
//!
//! - `Signal::new(value)`, `get`, `set`, `update` — ячейка значения; чтение
//!   возвращает клон, запись будит подписчиков.
//! - `Memo::new(fn)` — производное значение, считается лениво и кэшируется
//!   между проходами.
//! - `Effect::new(fn)` — побочный эффект; выполняется сразу при создании, потом
//!   на каждом flush, где его зависимости грязные.
//! - `batch(fn)` — копит записи и запускает эффекты один раз в конце внешнего
//!   батча.
//! - `untrack(fn)` — выполняет замыкание без подписки на прочитанное.
//! - `flush()` — выполняет запланированные эффекты; вызывается циклом кадра
//!   между обработкой событий и отрисовкой.
//! - `EffectScope` — владелец эффектов; `dispose` останавливает их и снимает
//!   подписки.
//!
//! Точные сигнатуры и семантика каждого примитива закреплены doc-тестами по
//! мере реализации; этот раздел — их контракт.
//!
//! # Пределы MVP
//!
//! Нет дифф-обновлений списков (`SignalVec`), нет асинхронных примитивов, нет
//! переиспользования слотов арены: узел живёт до сброса области. Глубина
//! графа ограничена только памятью.

