//! Реактивное ядро BRUL: сигналы, memo и эффекты.
//!
//! # Модель
//!
//! Граф однопоточный и живёт на UI-потоке вместе с рендером. Узел — `Signal`,
//! `Memo` или `Effect`; ребро — зависимость «этот узел читает тот». Сигнал
//! хранит список подписчиков, подписчик — список своих зависимостей. Списки —
//! `Vec` индексов: подписка добавляется без дублей, снимается перебором при
//! пересчёте. Для размера UI это не узкое место.
//!
//! Расчёт идёт в два такта:
//!
//! 1. запись в сигнал помечает грязными всех подписчиков вниз по графу и
//!    ставит эффекты в очередь, но ничего не считает;
//! 2. чтение грязного memo пересчитывает его и заново подписывается на
//!    прочитанное.
//!
//! Версии значений не сравниваются: memo с тем же результатом всё равно
//! пересчитается и разбудит подписчиков. Эффект — исключение из ленивости: его
//! никто не читает, поэтому он выполняется на [`flush`], не чаще одного раза за
//! проход; запись из эффекта добавляет ещё один проход.
//!
//! ```
//! use brul_reactive::{flush, Effect, Memo, Signal};
//!
//! let count = Signal::new(1);
//! let doubled = Memo::new(move || count.get() * 2);
//! let seen = std::rc::Rc::new(std::cell::Cell::new(0));
//! let runs = std::rc::Rc::clone(&seen);
//! let _effect = Effect::new(move || runs.set(doubled.get()));
//!
//! assert_eq!(seen.get(), 2);
//! count.set(5);
//! flush();
//! assert_eq!(seen.get(), 10);
//! ```
//!
//! # Инварианты
//!
//! - Связи графа — индексы в арене `Vec<Node>`; узлы не держат `Rc` друг
//!   друга, поэтому циклов подписок нет. Значения и замыкания лежат в
//!   типизированных ячейках, которые узел получает из арены.
//! - Пометка и очередь эффектов идут на явном стеке. Пересчёт memo может
//!   вкладываться в пересчёт другого memo, если один читает другой.
//! - Узел пересчитывается не больше одного раза за проход.
//! - Чтение подписывает только внутри вычисления (`Memo`, `Effect`). Вне их
//!   чтение подписки не создаёт; `untrack` выключает подписку на время
//!   замыкания.
//! - Запись из эффекта разрешена: она ставит в очередь ещё один проход того же
//!   flush, а не перезапускает текущий.
//! - Дескрипторы — индексы в арене, `!Send` и `!Sync`. Передать их в
//!   tokio-задачу нельзя: фоновое обновление приходит через канал на UI-поток.
//!
//! # Реализация
//!
//! `graph::notify` — push-такт: идёт по подписчикам на явном стеке, помечает
//! memo грязными и ставит каждый эффект в очередь один раз. `Memo::get` —
//! pull-такт: если узел грязный, он снимает старые зависимости, пересчитывает
//! значение и подписывается на прочитанное заново. [`flush`] разбирает очередь
//! эффектов до пустоты, поэтому запись из эффекта попадает в следующий проход.
//!
//! Ориентир — push-pull и ленивый пересчёт из
//! [alien-signals](https://github.com/stackblitz-labs/alien-signals) и
//! `reactive_graph`: их версии, флаги `Watched`/`Recursed` и сравнение значений
//! не переносились. Чужие движки изучаются как best practices, а не копируются
//! целиком.
//!
//! # Публичный API
//!
//! API намеренно узкий: без трейтов чтения и записи, guard-ов и асинхронного
//! планировщика.
//!
//! - `Signal::new(value)`, `get`, `set`, `update` — ячейка значения; чтение
//!   возвращает клон, запись будит подписчиков.
//! - `Memo::new(fn)` — производное значение, считается лениво и кэшируется
//!   между проходами.
//! - `Effect::new(fn)` — побочный эффект; выполняется сразу при создании, потом
//!   на каждом flush, где его зависимости грязные.
//! - `batch(fn)` — копит записи и запускает эффекты один раз в конце внешнего
//!   батча.
//! - `untrack(fn)` — выполняет замыкание без подписки на прочитанное.
//! - `flush()` — выполняет запланированные эффекты; вызывается циклом кадра
//!   между обработкой событий и отрисовкой.
//! - `EffectScope` — владелец эффектов; `dispose` останавливает их и снимает
//!   подписки.
//!
//! Точные сигнатуры и семантика каждого примитива закреплены doc-тестами; этот
//! раздел — их контракт.
//!
//! # Замеры
//!
//! `cargo bench -p brul-reactive` гоняет цепочку, ромб, много подписчиков и
//! батчи. Criterion сравнивает прогоны на одной машине; абсолютные числа
//! зависят от железа и в контракт не входят.
//!
//! # Пределы MVP
//!
//! Нет сравнения версий: изменение любого источника пересчитывает все грязные
//! memo вниз по графу, даже если значение не изменилось. Нет дифф-обновлений
//! списков (`SignalVec`), нет асинхронных примитивов, нет переиспользования
//! слотов арены: `dispose` только отписывает эффект, память не возвращается.
//! Глубина графа ограничена только памятью.

