use std::fmt::Write;

use brul_lang_schema::TYPES;

pub fn types_doc() -> String {
    let mut out = String::new();
    out.push_str("<!-- Generated by brul-lang-gen; do not edit. -->\n\n");
    out.push_str("# Language types\n\n");
    out.push_str("## Types\n\n");
    out.push_str("| Type | Literals | Note |\n");
    out.push_str("| --- | --- | --- |\n");
    for spec in TYPES {
        let name = if spec.payload.is_some() {
            format!("{}<T>", spec.name)
        } else {
            spec.name.to_owned()
        };
        let _ = writeln!(out, "| `{}` | {} | {} |", name, spec.literal, spec.note);
    }
    out
}
