use std::fmt::Write;

use brul_lang_schema::{ArgSpec, BUILTINS, TYPES};

pub fn types_doc() -> String {
    let mut out = String::new();
    out.push_str("<!-- Generated by brul-lang-gen; do not edit. -->\n\n");
    out.push_str("# Language types\n\n");
    out.push_str("## Types\n\n");
    out.push_str("| Type | Literals | Note |\n");
    out.push_str("| --- | --- | --- |\n");
    for spec in TYPES {
        let name = if spec.payload.is_some() {
            format!("{}<T>", spec.name)
        } else {
            spec.name.to_owned()
        };
        let _ = writeln!(out, "| `{}` | {} | {} |", name, spec.literal, spec.note);
    }
    out
}

fn argument_name(index: usize, argument: &ArgSpec) -> String {
    match argument {
        ArgSpec::Any => format!("v{index}"),
        ArgSpec::Function => "fn".to_owned(),
        ArgSpec::Value(name) => name.to_ascii_lowercase(),
    }
}

fn argument_type(argument: &ArgSpec) -> &'static str {
    match argument {
        ArgSpec::Any => "Any",
        ArgSpec::Function => "Function",
        ArgSpec::Value(name) => match *name {
            "Array" => "Array<Any>",
            other => other,
        },
    }
}

pub fn builtins_doc() -> String {
    let mut out = String::new();
    out.push_str("<!-- Generated by brul-lang-gen; do not edit. -->\n\n");
    out.push_str("# Language builtins\n\n");
    out.push_str("## Functions\n\n");
    out.push_str("| Function | Description |\n");
    out.push_str("| --- | --- |\n");
    for spec in BUILTINS {
        let arguments = spec
            .arguments
            .iter()
            .enumerate()
            .map(|(index, argument)| {
                format!(
                    "{}: {}",
                    argument_name(index, argument),
                    argument_type(argument)
                )
            })
            .collect::<Vec<_>>()
            .join(", ");
        let _ = writeln!(
            out,
            "| `{}({}): {}` | {} |",
            spec.name, arguments, spec.result, spec.note
        );
    }
    out
}
