use std::fmt::Write;

use brul_style_schema::{PROPERTIES, SHORTHANDS};

pub fn properties_doc() -> String {
    let mut out = String::new();
    out.push_str("<!-- Generated by brul-style-gen; do not edit. -->\n\n");
    out.push_str("# Style properties\n\n");
    out.push_str("## Properties\n\n");
    out.push_str("| Property | Type | Default | State | Target | Animatable |\n");
    out.push_str("| --- | --- | --- | --- | --- | --- |\n");
    for spec in PROPERTIES {
        writeln!(
            out,
            "| `{}` | `{:?}` | `{}` | `{:?}` | `{:?}` | `{}` |",
            spec.name, spec.ty, spec.default, spec.in_state, spec.target, spec.animatable
        )
        .unwrap();
    }
    out.push_str("\n## Shorthands\n\n");
    out.push_str("| Shorthand | Expands to | Parser |\n");
    out.push_str("| --- | --- | --- |\n");
    for spec in SHORTHANDS {
        let properties = spec
            .expands_to
            .iter()
            .map(|key| {
                PROPERTIES
                    .iter()
                    .find(|property| property.key == *key)
                    .map(|property| property.name)
                    .expect("shorthand references a known property")
            })
            .collect::<Vec<_>>()
            .join(", ");
        writeln!(
            out,
            "| `{}` | `{}` | `{:?}` |",
            spec.name, properties, spec.parser
        )
        .unwrap();
    }
    out
}
